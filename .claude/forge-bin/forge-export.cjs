#!/usr/bin/env node
'use strict';
/** forge-export: generate OpenCode / Codex / Gemini files from .claude/agents + .claude/skills.
 *  Usage: node forge-export.cjs <opencode|codex|gemini|all> [--check] [--root <dir>]
 *  Deterministic and idempotent (no timestamps). --check = drift test, exit 1 on any difference.
 *  Writes no credentials: provider keys are {env:VAR} references only. Plan: the any-model plan, layer L2 (owner docs, not shipped). */
const fs = require('fs');
const path = require('path');

const BEGIN = '<!-- BEGIN forge-export (generated, do not edit) -->';
const END = '<!-- END forge-export -->';
const TARGETS = ['opencode', 'codex', 'gemini'];

const nl = (s) => s.replace(/\r\n/g, '\n');

function splitFrontmatter(text) {
  const m = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(nl(text));
  if (!m) return { fm: {}, body: nl(text) };
  const fm = {};
  let key = null;
  for (const line of m[1].split('\n')) {
    const kv = /^([A-Za-z][\w-]*):\s*(.*)$/.exec(line);
    if (kv) { key = kv[1]; fm[key] = kv[2].trim(); if (fm[key] === '') fm[key] = []; }
    else if (key && /^\s+-\s+/.test(line) && Array.isArray(fm[key])) fm[key].push(line.replace(/^\s+-\s+/, '').trim());
    else if (key && typeof fm[key] === 'string' && /^\s+\S/.test(line)) fm[key] += ' ' + line.trim();
  }
  return { fm, body: m[2] };
}

function loadSources(root) {
  const agentsDir = path.join(root, '.claude', 'agents');
  const skillsDir = path.join(root, '.claude', 'skills');
  const agents = fs.existsSync(agentsDir) ? fs.readdirSync(agentsDir).filter((f) => f.endsWith('.md') && f !== 'AGENTS.md').sort().map((f) => {
    const { fm, body } = splitFrontmatter(fs.readFileSync(path.join(agentsDir, f), 'utf8'));
    return { id: f.replace(/\.md$/, ''), fm, body };
  }) : [];
  const skills = [];
  if (fs.existsSync(skillsDir)) {
    for (const d of fs.readdirSync(skillsDir).sort()) {
      const p = path.join(skillsDir, d, 'SKILL.md');
      if (!fs.existsSync(p)) continue;
      const { fm } = splitFrontmatter(fs.readFileSync(p, 'utf8'));
      skills.push({ dir: d, name: fm.name || d, description: String(fm.description || ''), license: fs.existsSync(path.join(skillsDir, d, 'LICENSE')) });
    }
  }
  return { agents, skills };
}

const header = (target, map) => [
  `Generated by forge-export (${target}) from .claude/agents and .claude/skills. Do not edit; re-run the generator.`,
  'The exported Forge is ADVICE, not ENFORCEMENT. Missing on this runtime:',
  ...map.limits.map((l) => `- ${l}`),
].join('\n');

const toolsOf = (fm) => (Array.isArray(fm.tools) ? fm.tools : String(fm.tools || '').split(',')).map((s) => s.trim()).filter(Boolean);

function permission(fm, map) {
  const tools = toolsOf(fm);
  const out = {};
  for (const g of ['edit', 'bash', 'webfetch']) out[g] = map.tools[g].some((t) => tools.includes(t)) ? 'allow' : 'deny';
  return out;
}

function opencodeFiles(src, map) {
  const files = {};
  const h = header('opencode', map);
  for (const a of src.agents) {
    const perm = permission(a.fm, map);
    const model = map.model[a.fm.model] ? map.model[a.fm.model].opencode : null;
    const skills = (Array.isArray(a.fm.skills) ? a.fm.skills : []).map((s) => `.claude/skills/${s}/SKILL.md`);
    const lines = ['---', `description: ${JSON.stringify(String(a.fm.description || a.id))}`, 'mode: subagent'];
    if (model) lines.push(`model: ${model}`);
    lines.push('permission:', ...Object.entries(perm).map(([k, v]) => `  ${k}: ${v}`), '---');
    const note = `<!-- ${h.replace(/\n/g, '\n     ')}\n     Dropped keys: ${map.dropped.join(', ')}. -->`;
    const skillBlock = skills.length ? `\nSkills to read when relevant:\n${skills.map((s) => `- ${s}`).join('\n')}\n` : '';
    files[`.opencode/agents/${a.id}.md`] = `${lines.join('\n')}\n${note}\n${skillBlock}${a.body.replace(/^\n+/, '\n')}`;
  }
  files['.opencode/opencode.json'] = JSON.stringify({
    $schema: 'https://opencode.ai/config.json',
    provider: {
      'forge-eigen-api': {
        npm: '@ai-sdk/openai-compatible',
        name: 'Forge own API (endpoint you choose; loopback or private network)',
        options: { baseURL: `{env:${map.provider.baseUrlEnv}}`, apiKey: `{env:${map.provider.keyEnv}}` },
      },
      'forge-ollama': {
        npm: '@ai-sdk/openai-compatible',
        name: 'Ollama (local)',
        options: { baseURL: map.provider.ollamaBase },
      },
    },
  }, null, 2) + '\n';
  return files;
}

function skillList(src) {
  return src.skills.map((s) => `- ${s.name}: .claude/skills/${s.dir}/SKILL.md${s.license ? ' (LICENSE beside it, keep the notice)' : ''}${s.description ? ' - ' + s.description.replace(/\s+/g, ' ').slice(0, 160) : ''}`).join('\n');
}
function agentList(src, map) {
  return src.agents.map((a) => {
    const p = permission(a.fm, map);
    return `- ${a.id}: ${String(a.fm.description || '').replace(/\s+/g, ' ').slice(0, 160)} (edit ${p.edit}, bash ${p.bash})`;
  }).join('\n');
}

function codexSection(src, map) {
  const sandbox = src.agents.some((a) => Object.values(permission(a.fm, map)).slice(0, 2).includes('allow')) ? 'workspace-write' : 'read-only';
  return [
    BEGIN, '## Forge export for Codex and OpenCode (generated)', '', header('codex', map), '',
    `Suggested Codex sandbox: ${sandbox} (never danger-full-access). Rules of this project: CLAUDE.md.`, '',
    '### Agents', agentList(src, map), '', '### Skills', skillList(src), '',
    '### Custom provider snippet (put in your own ~/.codex/config.toml; no credentials here)', '```toml',
    '[model_providers.forge_eigen]', 'name = "Forge own API"', `base_url = "<your endpoint, loopback or private network>"  # env ${map.provider.baseUrlEnv}`,
    `env_key = "${map.provider.keyEnv}"`, 'wire_api = "chat"', '```', END,
  ].join('\n');
}

function geminiFile(src, map) {
  return ['# GEMINI.md - Forge export (generated)', '', header('gemini', map), '',
    'Project rules: read CLAUDE.md and AGENTS.md first.', '', '## Agents', agentList(src, map), '', '## Skills', skillList(src), ''].join('\n');
}

function mergeMarkers(existing, section) {
  const text = nl(existing);
  const i = text.indexOf(BEGIN), j = text.indexOf(END);
  if (i >= 0 && j > i) return text.slice(0, i) + section + text.slice(j + END.length);
  return text.replace(/\n*$/, '\n\n') + section + '\n';
}

function generate(root, targets) {
  const map = JSON.parse(fs.readFileSync(path.join(root, '.claude', 'config', 'orchestration', 'runtime-map.json'), 'utf8'));
  const src = loadSources(root);
  const out = {};
  if (targets.includes('opencode')) Object.assign(out, opencodeFiles(src, map));
  if (targets.includes('gemini')) out['GEMINI.md'] = geminiFile(src, map);
  if (targets.includes('codex') || targets.includes('opencode')) {
    // D4: AGENTS.md serves both Codex and OpenCode; one generated section.
    const cur = fs.existsSync(path.join(root, 'AGENTS.md')) ? fs.readFileSync(path.join(root, 'AGENTS.md'), 'utf8') : '# AGENTS.md\n';
    out['AGENTS.md'] = mergeMarkers(cur, codexSection(src, map));
  }
  return out;
}

function run(root, targets, check) {
  const want = generate(root, targets);
  const diffs = [];
  for (const [rel, content] of Object.entries(want)) {
    const p = path.join(root, rel);
    const have = fs.existsSync(p) ? nl(fs.readFileSync(p, 'utf8')) : null;
    if (have === content) continue;
    diffs.push(rel);
    if (!check) { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, content); }
  }
  return { diffs, files: Object.keys(want) };
}

module.exports = { generate, run, splitFrontmatter, mergeMarkers, BEGIN, END, TARGETS };

if (require.main === module) {
  const args = process.argv.slice(2);
  // --help must never fall through to the default target "all" (that WRITES AGENTS.md/GEMINI.md).
  if (args.includes('--help') || args.includes('-h')) {
    console.log('Usage: node forge-export.cjs <opencode|codex|gemini|all> [--check] [--root <dir>]\n'
      + '  Writes the exports (default target all); --check only reports drift (exit 1). --help writes nothing.');
    process.exit(0);
  }
  const unknown = args.find((a) => a.startsWith('-') && a !== '--check' && a !== '--root');
  if (unknown) { console.error('forge-export: unknown option ' + unknown + ' (nothing written; see --help)'); process.exit(2); }
  const ri = args.indexOf('--root');
  const root = ri >= 0 ? path.resolve(args[ri + 1]) : path.resolve(__dirname, '..', '..');
  const t = args.find((a, i) => !a.startsWith('--') && i !== ri + 1) || 'all';
  const targets = t === 'all' ? TARGETS : [t];
  if (!targets.every((x) => TARGETS.includes(x))) { console.error('target: opencode|codex|gemini|all'); process.exit(2); }
  const check = args.includes('--check');
  const r = run(root, targets, check);
  if (check) {
    if (r.diffs.length) { console.error('DRIFT: ' + r.diffs.join(', ') + ' (run forge-export to regenerate)'); process.exit(1); }
    console.log(`forge-export: no drift (${r.files.length} files)`); process.exit(0);
  }
  console.log(`forge-export: ${r.files.length} files, ${r.diffs.length} written`);
}
