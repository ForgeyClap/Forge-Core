// ---- fragment ----------------------------------------------------------------------------------------------------
function loadFragment(file) {
  const j = readJsonLoose(file); if (!j) return { error: 'not readable as JSON: ' + file };
  if (!settingsMerge.fullyValidShape(j) || !j.hooks || !j.permissions || !Array.isArray(j.permissions.deny)) return { error: 'unexpected shape: ' + file };
  return { fragment: { hooks: j.hooks, permissions: { deny: j.permissions.deny.slice() } } };
}
// Canonical key order, so an owner /plugin re-order of settings.json is no drift: entry matcher, hooks; hook type, command, timeout, async; then the rest.
const ordered = (o, first) => (o && typeof o === 'object' && !Array.isArray(o) ? Object.fromEntries(first.filter((k) => k in o).map((k) => [k, o[k]]).concat(Object.entries(o).filter(([k]) => !first.includes(k)))) : o);
const canonicalHooks = (hooks) => Object.fromEntries(Object.entries(hooks || {}).map(([ev, list]) => [ev, !Array.isArray(list) ? list : list.map((e) => { const en = ordered(e, ['matcher', 'hooks']); return en && Array.isArray(en.hooks) ? Object.assign(en, { hooks: en.hooks.map((h) => ordered(h, ['type', 'command', 'timeout', 'async'])) }) : en; })]));
function fragmentFromSettings(settings) { const s = settings || {}; return { _doc: FRAGMENT_DOC, hooks: canonicalHooks(s.hooks), permissions: { deny: (s.permissions && Array.isArray(s.permissions.deny)) ? s.permissions.deny.slice() : [] } }; }
function fragmentText(settings) { return JSON.stringify(fragmentFromSettings(settings), null, 2) + '\n'; }

// ---- plan --------------------------------------------------------------------------------------------------------
function pluginEnabled(root, opts) {
  const home = homeOf(opts);
  const files = [path.join(root, '.claude', 'settings.json'), path.join(root, '.claude', 'settings.local.json')];
  if (home) files.push(path.join(home, '.claude', 'settings.json'));
  const on = (ep) => !!ep && typeof ep === 'object' && Object.keys(ep).some((k) => /^forge@/i.test(k) && ep[k] === true);
  return files.some((f) => { const j = readJsonLoose(f); return on(j && j.enabledPlugins); });
}
function hooksInfo(root, fragment, opts) {
  const tools = [];
  for (const ev of Object.keys(fragment.hooks)) for (const g of fragment.hooks[ev] || []) for (const h of (g && g.hooks) || []) {
    const m = HOOK_CMD_RE.exec(String((h && h.command) || '').trim());
    if (m && !tools.includes(m[1])) tools.push(m[1]);
  }
  const plugin = pluginEnabled(root, opts);
  const missing = tools.filter((t) => !isFile(path.join(root, '.claude', 'forge-bin', t)));
  const mode = plugin ? 'plugin' : (tools.length && !missing.length ? 'project' : (missing.length === tools.length ? 'none' : 'partial'));
  const cur = readJsonLoose(path.join(root, '.claude', 'settings.json'));
  const inSettings = !!(cur && cur.hooks && typeof cur.hooks === 'object') && Object.values(cur.hooks).some((list) => Array.isArray(list)
    && list.some((g) => g && Array.isArray(g.hooks) && g.hooks.some((h) => h && settingsMerge.isForgeHookCommand(h.command))));
  return { mode, tools, missing, plugin, double: plugin && inSettings };
}
function settingsStep(root, source) {
  const file = path.join(root, '.claude', 'settings.json'); const base = { id: 'settings', file, source };
  if (!source.hooks && !source.permissions) return Object.assign(base, { action: 'none', detail: 'nothing to merge' });
  const t = settingsMerge.readTargetKind(file);
  const hooksN = (src) => Object.values(src.hooks || {}).reduce((n, l) => n + l.reduce((k, g) => k + ((g && g.hooks) || []).length, 0), 0);
  if (t.kind === 'missing') return Object.assign(base, { action: 'create', hooks_added: hooksN(source), deny_added: source.permissions ? source.permissions.deny.length : 0 });
  const refuse = (why) => Object.assign(base, { action: 'refuse', detail: why });
  if (t.kind === 'unreadable') return refuse('cannot be read safely (' + t.error + ')');
  let json;
  try { json = JSON.parse(stripBom(t.raw)); } catch (e) { return refuse('is not valid JSON (' + e.message + ')'); }
  if (!settingsMerge.validShape(json) || !guards.deepValidateHooksShape(json)) return refuse('has an unexpected hooks/permissions shape');
  const risks = guards.scanJsonRisks(stripBom(t.raw));
  if (risks.duplicateKeys.length || risks.unsafeNumbers.length) return refuse('has duplicate keys or numbers a rewrite would change');
  const m = settingsMerge.mergeForgeSettings(json, source);
  const n = m.added.length + m.adjusted.length + m.upgraded.length + m.deny_added.length;
  return Object.assign(base, { action: n ? 'merge' : 'none', hooks_added: m.added_detail.length, deny_added: m.deny_added.length, upgraded: m.upgraded.length, adjusted: m.adjusted.length });
}
function claudeMdStep(root, layout) {
  const rootMd = path.join(root, 'CLAUDE.md'); const dotMd = path.join(root, '.claude', 'CLAUDE.md');
  const file = !lstatOf(rootMd) && isFile(dotMd) ? dotMd : rootMd; // an existing .claude/CLAUDE.md is used, never a second file
  const base = { id: 'claude_md', file };
  const st = lstatOf(file);
  if (!st) return Object.assign(base, { action: 'create', content: '# ' + path.basename(root) + '\n\n' + claudeBlock(layout, '\n') + '\n' });
  if (!st.isFile()) return Object.assign(base, { action: 'refuse', detail: 'is not a regular file (a link or a folder)' });
  let raw;
  try { raw = fs.readFileSync(file, 'utf8'); } catch (e) { return Object.assign(base, { action: 'refuse', detail: 'cannot be read (' + e.message + ')' }); }
  const eol = raw.includes('\r\n') ? '\r\n' : '\n';
  const want = claudeBlock(layout, eol);
  const begins = raw.split(BEGIN_PREFIX).length - 1;
  const ends = raw.split(END).length - 1;
  if (!begins && !ends) {
    const sep = raw === '' ? '' : (raw.endsWith(eol) ? eol : eol + eol);
    return Object.assign(base, { action: 'append', raw, content: raw + sep + want + eol });
  }
  const bi = raw.indexOf(BEGIN_PREFIX);
  const ei = raw.indexOf(END);
  if (begins !== 1 || ends !== 1 || ei < bi) return Object.assign(base, { action: 'refuse', detail: 'has broken forge-init markers (need exactly one begin before one end); fix them by hand' });
  if (raw.slice(bi, ei + END.length) === want) return Object.assign(base, { action: 'none' });
  return Object.assign(base, { action: 'update', raw, content: raw.slice(0, bi) + want + raw.slice(ei + END.length) });
}

/** planInit(opts) -> plan. Read-only. opts: {root, layout, noDeny, env, home, now, fragmentPath}. */
function planInit(opts) {
  const o = opts || {};
  const env = o.env || process.env;
  const root = path.resolve(o.root || process.cwd());
  const plan = { schema: SCHEMA, root, ok: false, steps: [], notes: [] };
  const tc = targetCheck(root, Object.assign({}, o, { env }));
  if (!tc.ok) return Object.assign(plan, { refused: tc.code });
  const fr = loadFragment(o.fragmentPath || FRAGMENT_PATH);
  if (fr.error) return Object.assign(plan, { refused: 'r_fragment', refusedDetail: fr.error });
  try { return buildPlan(plan, root, env, o, fr.fragment); } catch (e) {
    if (e && e.name === 'ForgePathError') return Object.assign(plan, { refused: 'r_paths', refusedDetail: e.message });
    throw e;
  }
}
function buildPlan(plan, root, env, o, fragment) {
  const current = forgePaths.layout(root, { env });
  if (o.layout === 'legacy' && current === 'forge') return Object.assign(plan, { refused: 'r_layout' });
  const layout = o.layout || current;
  const day = (o.now || new Date()).toISOString().slice(0, 10);
  const stateRoot = forgePaths.resolve(root, 'state_root', { env });
  const pick = (key) => { const d = forgePaths.stateDirFor(root, key, { env }); return layout === 'forge' ? d.forge : d.legacy; };
  plan.layout = layout;
  plan.backupDir = path.join(pick('backups'), 'forge-init');
  if (layout === 'forge' && current === 'legacy') {
    plan.steps.push({ id: 'layout', file: stateRoot, action: 'create', dirs: [stateRoot, forgePaths.stateDirFor(root, 'memory', { env }).forge] });
    if (['runs', 'scribe', 'tickets', 'research'].some((k) => isDir(forgePaths.stateDirFor(root, k, { env }).legacy))) plan.notes.push('legacy_state');
  } else plan.steps.push({ id: 'layout', file: layout === 'forge' ? stateRoot : path.join(root, '.claude'), action: 'none' });
  const mem = forgePaths.stateDirFor(root, 'memory', { env });
  for (const name of MEMORY_FILES) {
    const legacyFile = path.join(mem.legacy, name);
    const target = layout === 'forge' ? path.join(mem.forge, name) : legacyFile;
    if (lstatOf(target)) plan.steps.push({ id: 'memory', file: target, action: 'keep' });
    else if (layout === 'forge' && lstatOf(legacyFile)) plan.steps.push({ id: 'memory', file: legacyFile, action: 'keep-legacy' });
    else plan.steps.push({ id: 'memory', file: target, action: 'create', content: memoryTemplate(name, path.basename(root), day, layout) });
  }
  const hi = hooksInfo(root, fragment, o);
  plan.hooks = { mode: hi.mode, missing: hi.missing, plugin: hi.plugin, double: hi.double };
  if (hi.mode !== 'project') plan.notes.push('h_' + hi.mode); // h_plugin | h_none | h_partial
  if (hi.double) plan.notes.push('h_double');
  const source = {};
  if (hi.mode === 'project') source.hooks = fragment.hooks;
  if (!o.noDeny) source.permissions = { deny: fragment.permissions.deny };
  plan.steps.push(settingsStep(root, source));
  plan.steps.push(claudeMdStep(root, layout));
  try { for (const n of fs.readdirSync(path.join(root, '.claude'))) if (n.startsWith(TMP_PREFIX)) plan.leftovers = (plan.leftovers || []).concat('.claude/' + n); } catch { /* no .claude yet */ }
  if (plan.leftovers) plan.notes.push('leftover');
  plan.changes = plan.steps.filter((s) => CHANGE_ACTIONS.has(s.action)).length;
  plan.refusedSteps = plan.steps.filter((s) => s.action === 'refuse').length;
  plan.ok = true;
  return plan;
}

// ---- apply -------------------------------------------------------------------------------------------------------
/** lostSettings(before, after) -> problems[]: a pre-existing hook that is gone (user hooks must survive byte-for-byte as
 *  JSON; a Forge hook may only be upgraded to a newer form of the same script), a user deny rule removed, changed or
 *  reordered, or any other pre-existing key that changed. */
function lostSettings(before, after) {
  const problems = [];
  const b = before || {};
  const a = after || {};
  const bh = b.hooks || {};
  const ah = a.hooks || {};
  for (const ev of Object.keys(bh)) for (const g of bh[ev] || []) for (const h of (g && Array.isArray(g.hooks) ? g.hooks : [])) {
    const peers = (Array.isArray(ah[ev]) ? ah[ev] : []).filter((x) => x && x.matcher === g.matcher).flatMap((x) => (Array.isArray(x.hooks) ? x.hooks : []));
    const forge = !!h && settingsMerge.isForgeHookCommand(h.command);
    const kept = forge
      ? peers.some((x) => x && x.type === h.type && settingsMerge.forgeScriptName(x.command) === settingsMerge.forgeScriptName(h.command))
      : peers.some((x) => JSON.stringify(x) === JSON.stringify(h));
    if (!kept) problems.push('hook ' + ev + (g.matcher !== undefined ? '[' + g.matcher + ']' : '') + ' ' + JSON.stringify(h && h.command));
  }
  const bd = b.permissions && Array.isArray(b.permissions.deny) ? b.permissions.deny : [];
  const ad = a.permissions && Array.isArray(a.permissions.deny) ? a.permissions.deny : [];
  if (bd.some((r, i) => ad[i] !== r)) problems.push('permissions.deny: an existing rule was removed, changed or moved');
  for (const k of Object.keys(b)) if (k !== 'hooks' && k !== 'permissions' && JSON.stringify(b[k]) !== JSON.stringify(a[k])) problems.push('key ' + k + ' changed');
  const bp = b.permissions || {};
  for (const k of Object.keys(bp)) if (k !== 'deny' && JSON.stringify(bp[k]) !== JSON.stringify((a.permissions || {})[k])) problems.push('permissions.' + k + ' changed');
  return problems;
}
function applySettings(root, step, plan, opts) {
  const tool = opts.mergeTool || settingsMerge;
  mkdirIn(root, path.dirname(step.file));
  assertWritable(root, step.file);
  const beforeRaw = isFile(step.file) ? fs.readFileSync(step.file, 'utf8') : null;
  if (step.action === 'merge') mkdirIn(root, plan.backupDir);
  const tmp = assertWritable(root, path.join(root, '.claude', TMP_PREFIX + process.pid + '-' + Math.random().toString(36).slice(2, 8) + '.json'));
  let r;
  try {
    fs.writeFileSync(tmp, JSON.stringify(step.source, null, 2) + '\n', { encoding: 'utf8', flag: 'wx' });
    r = tool.applySettingsMerge({ target: step.file, source: tmp, backupDir: step.action === 'merge' ? plan.backupDir : path.dirname(step.file), projectRoot: root });
  } finally { try { fs.unlinkSync(tmp); } catch { /* already gone */ } }
  if (!r || r.ok !== true) return { result: 'refuse', detail: (r && (r.message || r.error || r.status)) || 'merge failed' };
  if (beforeRaw !== null) {
    const afterRaw = fs.readFileSync(step.file, 'utf8');
    let problems;
    try { problems = lostSettings(JSON.parse(stripBom(beforeRaw)), JSON.parse(stripBom(afterRaw))); } catch (e) { problems = ['result is not valid JSON (' + e.message + ')']; }
    if (problems.length) {
      writeReplace(root, step.file, beforeRaw, afterRaw);
      return { result: 'refuse', detail: 'the merge did not keep your own settings (' + problems[0] + '); the original file was put back' + (r.backupPath ? ', backup: ' + rel(root, r.backupPath) : '') };
    }
  }
  return { result: r.status === 'noop' ? 'none' : step.action, backup: r.backupPath ? rel(root, r.backupPath) : null };
}
function applyStep(root, step, plan, opts) {
  if (!CHANGE_ACTIONS.has(step.action)) return { result: step.action };
  if (step.id === 'layout') { for (const d of step.dirs) mkdirIn(root, d); return { result: 'create' }; }
  if (step.id === 'memory') {
    try { writeNew(root, step.file, step.content); } catch (e) { if (e && e.code === 'EEXIST') return { result: 'keep' }; throw e; }
    return { result: 'create' };
  }
  if (step.id === 'settings') return applySettings(root, step, plan, opts);
  if (step.action === 'create') {
    try { writeNew(root, step.file, step.content); } catch (e) { if (e && e.code === 'EEXIST') return { result: 'refuse', detail: 'CLAUDE.md appeared while running; run again' }; throw e; }
    return { result: 'create' };
  }
  mkdirIn(root, plan.backupDir);
  const bk = guards.writeExclusiveUnique(assertWritable(root, plan.backupDir), path.basename(step.file) + '.forge-init-bak', '', step.raw, {});
  if (!bk.ok) return { result: 'refuse', detail: 'no backup could be made first (' + bk.reason + ')' };
  writeReplace(root, step.file, step.content, step.raw);
  return { result: step.action, backup: rel(root, bk.path) };
}
/** applyInit(opts) -> plan with per-step `result`. opts.yes=false -> dry run (nothing written). */
function applyInit(opts) {
  const o = opts || {};
  const plan = planInit(o);
  if (!plan.ok || !o.yes) return Object.assign(plan, { dryRun: !o.yes });
  plan.dryRun = false;
  for (const step of plan.steps) {
    let res;
    try { res = applyStep(plan.root, step, plan, o); } catch (e) {
      res = { result: 'refuse', detail: e instanceof InitError ? e.code + ' ' + e.detail : String((e && e.message) || e) };
    }
    Object.assign(step, res);
  }
  plan.changes = plan.steps.filter((s) => CHANGE_ACTIONS.has(s.result)).length;
  plan.refusedSteps = plan.steps.filter((s) => s.result === 'refuse').length;
  return plan;
}
function checkInit(opts) {
  const plan = planInit(opts);
  return Object.assign(plan, { initialised: plan.ok && plan.changes === 0 && plan.refusedSteps === 0 });
}

// ---- output + CLI ------------------------------------------------------------------------------------------------
function detailOf(s, plan) {
  if (s.id === 'layout') return ' (layout ' + plan.layout + ')';
  if (s.id === 'settings' && s.hooks_added !== undefined && CHANGE_ACTIONS.has(s.action)) return ' (+' + s.hooks_added + ' hook(s), +' + s.deny_added + ' deny rule(s)' + (s.upgraded ? ', ' + s.upgraded + ' upgraded' : '') + ')';
  return s.detail ? ' (' + s.detail + ')' : '';
}
function render(plan, cmd, lang) {
  if (!plan.ok) return [say(lang, plan.refused, plan.refused === 'r_fragment' ? plan.refusedDetail : plan.root), say(lang, 'nothing')];
  const L = ['Forge init: ' + plan.root + ' (layout ' + plan.layout + ', hooks ' + plan.hooks.mode + ')'];
  for (const s of plan.steps) {
    const act = s.result || s.action;
    L.push('  ' + (ACTION_LABEL[act] || [act, act])[lang === 'nl' ? 1 : 0].padEnd(14) + rel(plan.root, s.file) + (s.id === 'claude_md' ? ' (pointer block)' : '') + detailOf(s, plan) + (s.backup ? ' [backup ' + s.backup + ']' : ''));
  }
  for (const n of plan.notes) L.push('  ' + say(lang, n, n === 'h_partial' ? plan.hooks.missing.length : (plan.leftovers || []).join(', ')));
  if (cmd === 'check') L.push(say(lang, plan.initialised ? 'ok' : 'not', plan.root, plan.changes + plan.refusedSteps));
  else if (plan.dryRun) L.push(plan.changes ? say(lang, 'dry') : say(lang, 'same'));
  else if (plan.refusedSteps) L.push(say(lang, 'failed', plan.root, plan.refusedSteps));
  else L.push(plan.changes ? say(lang, 'done', plan.root, plan.changes) : say(lang, 'same'));
  return L;
}
function toJson(plan, cmd) {
  const steps = plan.steps.map((s) => {
    const out = { id: s.id, path: rel(plan.root, s.file), action: s.action };
    for (const k of ['result', 'detail', 'backup', 'hooks_added', 'deny_added', 'upgraded']) if (s[k] !== undefined) out[k] = s[k];
    return out;
  });
  return { schema: SCHEMA, cmd, root: plan.root, ok: plan.ok, refused: plan.refused || null, message: plan.ok ? null : render(plan, cmd, 'en')[0], layout: plan.layout || null, hooks: plan.hooks || null,
    steps, notes: plan.notes, changes: plan.changes || 0, refused_steps: plan.refusedSteps || 0, dry_run: !!plan.dryRun, initialised: plan.initialised };
}
function parseArgs(argv) {
  const a = { cmd: argv[0] || null, root: null, layout: null, yes: false, json: false, lang: 'en', noDeny: false, home: undefined, devRoot: null, write: false, error: null };
  const value = (i, f) => { const v = argv[i + 1]; if (v === undefined || v.startsWith('--')) { a.error = f + ' needs a value'; return null; } return v; };
  for (let i = 1; i < argv.length && !a.error; i++) {
    const f = argv[i];
    if (f === '--root' || f === '--layout' || f === '--lang' || f === '--home' || f === '--dev-root') {
      const v = value(i, f); i++;
      if (v === null) break;
      if (f === '--root') a.root = v; else if (f === '--layout') a.layout = v; else if (f === '--lang') a.lang = v;
      else if (f === '--home') a.home = v === 'none' ? null : v; else a.devRoot = v;
    } else if (f === '--yes') a.yes = true; else if (f === '--json') a.json = true; else if (f === '--no-deny') a.noDeny = true;
    else if (f === '--write') a.write = true; else a.error = 'unknown argument ' + f;
  }
  if (!a.error && !['plan', 'apply', 'check', 'fragment'].includes(a.cmd)) a.error = 'unknown command ' + (a.cmd || '(none)');
  if (!a.error && a.layout !== null && !['legacy', 'forge'].includes(a.layout)) a.error = '--layout must be legacy or forge';
  if (!a.error && !['en', 'nl'].includes(a.lang)) a.error = '--lang must be en or nl';
  if (!a.error && a.yes && a.cmd !== 'apply') a.error = '--yes only belongs to apply';
  if (!a.error && a.write && a.cmd !== 'fragment') a.error = '--write only belongs to fragment';
  if (!a.error && a.cmd === 'check' && a.layout !== null) a.error = 'check takes no --layout';
  if (!a.error && (a.cmd === 'fragment') !== (a.devRoot !== null)) a.error = '--dev-root belongs to fragment (and fragment needs it)';
  return a;
}
const USAGE = 'Usage: node forge-init.cjs plan|apply|check [--root <dir>] [--layout legacy|forge] [--no-deny] [--yes] [--json] [--lang en|nl]\n'
  + '       node forge-init.cjs fragment --dev-root <dir> [--write]\n';
function fragmentCli(devRoot, write, out) {
  const root = path.resolve(devRoot);
  if (!isDevTree(root)) { out.err('forge-init fragment: ' + root + ' is not the Forge development tree (' + DEV_TREE_MARKER.join('/') + ')\n'); return EXIT.refused; }
  const settings = readJsonLoose(path.join(root, '.claude', 'settings.json'));
  if (!settings) { out.err('forge-init fragment: .claude/settings.json is not readable JSON\n'); return EXIT.refused; }
  const file = path.join(root, ...FRAGMENT_REL);
  const want = fragmentText(settings);
  let cur = null;
  try { cur = fs.readFileSync(file, 'utf8'); } catch { cur = null; }
  if (cur === want) { out.log('forge-init fragment: current (' + FRAGMENT_REL.join('/') + ')\n'); return EXIT.ok; }
  if (!write) { out.log('forge-init fragment: DRIFT, ' + FRAGMENT_REL.join('/') + ' differs from .claude/settings.json; run with --write\n'); return EXIT.notReady; }
  mkdirIn(root, path.dirname(file));
  fs.writeFileSync(assertWritable(root, file), want, 'utf8');
  out.log('forge-init fragment: written (' + FRAGMENT_REL.join('/') + ')\n');
  return EXIT.ok;
}
function main(argv, io) {
  const out = io || { log: (s) => process.stdout.write(s), err: (s) => process.stderr.write(s) };
  const a = parseArgs(argv);
  if (a.error) { out.err('forge-init: ' + a.error + '\n' + USAGE); return EXIT.refused; }
  if (a.cmd === 'fragment') return fragmentCli(a.devRoot, a.write, out);
  const opts = { root: a.root, layout: a.layout, noDeny: a.noDeny, home: a.home, yes: a.yes };
  const plan = a.cmd === 'check' ? checkInit(opts) : (a.cmd === 'apply' ? applyInit(opts) : Object.assign(planInit(opts), { dryRun: true }));
  if (a.json) out.log(JSON.stringify(toJson(plan, a.cmd), null, 2) + '\n');
  else out[plan.ok ? 'log' : 'err'](render(plan, a.cmd, a.lang).join('\n') + '\n');
  if (!plan.ok) return EXIT.refused;
  if (a.cmd === 'check') return plan.initialised ? EXIT.ok : EXIT.notReady;
  return plan.refusedSteps ? EXIT.notReady : EXIT.ok;
}

