/**
 * forge-init.cjs - modernization WP 3.1: `/forge init`, step 2 of the two-step install (step 1: add the Forge plugin,
 * or run the central installer). Sets ONE project folder up for Forge, idempotently. Zero dependencies.
 *
 *   node forge-init.cjs plan  [--root <dir>] [--layout legacy|forge] [--no-deny] [--json] [--lang en|nl]
 *   node forge-init.cjs apply [--root <dir>] [--layout legacy|forge] [--no-deny] [--yes] [--json] [--lang en|nl]
 *   node forge-init.cjs check [--root <dir>] [--no-deny] [--json] [--lang en|nl]
 *   node forge-init.cjs fragment --dev-root <dir> [--write]      maintainer: regenerate the shipped settings fragment
 * --root defaults to the current folder; `apply` is a dry run unless --yes; `--home <dir|none>` = where user-level settings
 * are read for plugin detection (tests). exit: 0 ok (check: initialised) · 1 check: not initialised / apply: a step was
 * refused / fragment: drift · 2 refused target or bad usage (nothing written)
 *
 * What apply writes, ONLY inside --root (every write passes assertWritable: lexically inside, real path inside, no
 * symlink/junction below the root):
 *   1. layout: legacy by default (state in .claude/forge-*); `--layout forge` creates .forge/ and .forge/memory/.
 *   2. memory: the five FORGE_*.md files from the templates below, created only when absent (never overwritten). In the
 *      .forge layout a legacy .claude/FORGE_*.md is kept and not shadowed (forge-paths readers fall back to it).
 *   3. .claude/settings.json: merged by forge-settings-merge.cjs (the hardened merge forge-sync uses: backup first,
 *      append-only, idempotent) from config/orchestration/forge-init.fragment.json. Deny rules are appended after the
 *      user's own (never removed, changed or reordered); hooks only when every hook script is in <root>/.claude/
 *      forge-bin/ and the Forge plugin is not enabled (a plugin brings its own hooks; adding them again would run every
 *      hook twice). A guard then re-reads the file and restores the original bytes if any pre-existing hook, deny rule
 *      or other key did not survive.
 *   4. CLAUDE.md (or an existing .claude/CLAUDE.md): one pointer block between the forge-init markers, created,
 *      appended or replaced in place; text outside the markers is never changed; malformed markers are refused.
 * Backups of changed files go to <backups state dir>/forge-init/ (forge-paths: .claude/forge-backups or .forge/backups).
 * Plugin-safe: the project root comes only from --root or the current folder; the one read relative to this script is
 * the shipped config fragment (config/ sits next to scripts/ in the plugin).
 */
