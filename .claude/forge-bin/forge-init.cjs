// ---- small fs helpers --------------------------------------------------------------------------------------------
class InitError extends Error { constructor(code, detail) { super(code + ': ' + detail); this.code = code; this.detail = detail; } }
const fold = (p) => (process.platform === 'win32' ? path.resolve(p).toLowerCase() : path.resolve(p));
const samePath = (a, b) => fold(a) === fold(b);
function isInside(base, p) { const r = path.relative(base, p); return r === '' || (!r.startsWith('..') && !path.isAbsolute(r)); }
function lstatOf(p) { try { return fs.lstatSync(p); } catch { return null; } }
const isFile = (p) => { const s = lstatOf(p); return !!s && s.isFile(); };
const isDir = (p) => { const s = lstatOf(p); return !!s && s.isDirectory(); };
const stripBom = (s) => (s.charCodeAt(0) === 0xfeff ? s.slice(1) : s);
function readJsonLoose(p) { try { return JSON.parse(stripBom(fs.readFileSync(p, 'utf8'))); } catch { return null; } }
function rel(root, p) { return path.relative(root, p).split(path.sep).join('/') || '.'; }

/** assertWritable(root, p) -> p. THE isolation guard: every write target must lie strictly below root, both lexically
 *  and by real path, and no existing path component between root and p may be a symlink or junction. */
function assertWritable(root, p) {
  const abs = path.resolve(p);
  if (samePath(abs, root) || !isInside(root, abs)) throw new InitError('outside-root', abs);
  for (let cur = abs; !samePath(cur, root); cur = path.dirname(cur)) {
    const st = lstatOf(cur);
    if (st && st.isSymbolicLink()) throw new InitError('link-below-root', cur);
    if (path.dirname(cur) === cur) throw new InitError('outside-root', abs);
  }
  if (!guards.containedWithin(root, abs)) throw new InitError('outside-root', abs);
  return abs;
}
function mkdirIn(root, dir) { assertWritable(root, dir); fs.mkdirSync(dir, { recursive: true }); assertWritable(root, dir); }
function writeNew(root, file, content) {
  if (!samePath(path.dirname(file), root)) mkdirIn(root, path.dirname(file));
  fs.writeFileSync(assertWritable(root, file), content, { encoding: 'utf8', flag: 'wx' });
}
/** writeReplace: temp sibling + rename, refused when the file changed since it was read (expectedRaw). */
function writeReplace(root, file, content, expectedRaw) {
  assertWritable(root, file);
  const tmp = assertWritable(root, file + '.' + process.pid + '.' + Math.random().toString(36).slice(2, 8) + '.tmp');
  fs.writeFileSync(tmp, content, { encoding: 'utf8', flag: 'wx' });
  let cur = null;
  try { cur = fs.readFileSync(file, 'utf8'); } catch { cur = null; }
  if (cur !== expectedRaw) { try { fs.unlinkSync(tmp); } catch { /* gone */ } throw new InitError('changed-on-disk', file); }
  fs.renameSync(tmp, file);
}

// ---- target checks -----------------------------------------------------------------------------------------------
function homeOf(opts) {
  if (opts.home === null) return null;
  if (typeof opts.home === 'string' && opts.home.trim()) return path.resolve(opts.home);
  try { return path.resolve(os.homedir()); } catch { return null; }
}
function systemDirs(env) {
  const inside = [env.APPDATA, env.LOCALAPPDATA, env.PROGRAMDATA, env.ProgramData, env.ProgramFiles, env['ProgramFiles(x86)'], env.SystemRoot, env.windir];
  const exact = [env.TEMP, env.TMP];
  try { exact.push(os.tmpdir()); } catch { /* none */ }
  const clean = (l) => l.filter((p) => typeof p === 'string' && p.trim()).map((p) => path.resolve(p));
  return { inside: clean(inside), exact: clean(exact).concat(clean(inside)) };
}
function isDevTree(dir) { const j = readJsonLoose(path.join(dir, ...DEV_TREE_MARKER)); return !!(j && j.dev_tree === true); }

/** targetCheck(root, opts) -> {ok:true} | {ok:false, code}. Read-only; nothing is ever written on a refusal. */
function targetCheck(root, opts) {
  const env = opts.env || process.env;
  const st = lstatOf(root);
  if (!st) return { ok: false, code: 'r_missing' };
  if (st.isSymbolicLink()) return { ok: false, code: 'r_symlink' };
  if (!st.isDirectory()) return { ok: false, code: 'r_missing' };
  if (path.parse(root).root === root) return { ok: false, code: 'r_drive' };
  for (const h of [homeOf({}), homeOf(opts)].filter(Boolean)) {
    if (samePath(root, h)) return { ok: false, code: 'r_home' };
    if (isInside(path.join(h, '.claude'), root)) return { ok: false, code: 'r_global' };
  }
  const sys = systemDirs(env);
  if (sys.exact.some((d) => samePath(d, root)) || sys.inside.some((d) => isInside(d, root))) return { ok: false, code: 'r_system' };
  if (isDevTree(root)) return { ok: false, code: 'r_devtree' };
  if (!PROJECT_MARKERS.some((m) => lstatOf(path.join(root, m)))) return { ok: false, code: 'r_noproject' };
  if (typeof env.FORGE_STATE_DIR === 'string' && env.FORGE_STATE_DIR.trim()) {
    let sr = null; try { sr = forgePaths.resolve(root, 'state_root', { env }); } catch { sr = null; }
    if (!sr || samePath(sr, root) || !isInside(root, sr)) return { ok: false, code: 'r_statedir' };
  }
  return { ok: true };
}

